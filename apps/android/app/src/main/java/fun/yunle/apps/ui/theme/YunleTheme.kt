@Composable
internal fun YunleTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    MaterialTheme(
        colorScheme = if (darkTheme) YunleDarkColorScheme else YunleLightColorScheme,
        shapes = YunleShapes,
        content = content,
    )
}
