import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const mediaOrigin = 'https://yunlefun-cos-1253292018.cos.ap-shanghai.myqcloud.com'
export const catalogPath = 'assets/catalog/app-assets.json'
export const catalogURL = 'https://icons.yunle.fun/app-assets/manifest.json'
const catalogMirrorURL = 'https://raw.githubusercontent.com/YunLeFun/icons/main/assets/catalog/app-assets.json'

export async function readOnlineCatalog(fetchCatalog = fetch) {
  try {
    const response = await fetchCatalog(catalogURL, { signal: AbortSignal.timeout(30_000) })
    if (!response.ok)
      throw new Error(`HTTP ${response.status}`)
    return await response.text()
  }
  catch (error) {
    console.warn(`Central catalog site unavailable (${error.message}); reading its GitHub source: ${catalogMirrorURL}`)
    const response = await fetchCatalog(catalogMirrorURL, { signal: AbortSignal.timeout(30_000) })
    if (!response.ok)
      throw new Error(`Cannot read the central icon catalog source: HTTP ${response.status}`)
    return await response.text()
  }
}

export function readDesktopAssets(source) {
  const manifest = JSON.parse(source)
  if (manifest.schemaVersion !== 1 || !Array.isArray(manifest.assets) || !manifest.assets.length)
    throw new Error('Expected a non-empty YunLeFun/icons schemaVersion 1 catalog')
  const slugs = new Set()
  const urls = new Set()
  const entries = manifest.assets.map(({ slug, desktopAsset }) => {
    if (typeof slug !== 'string' || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug) || slugs.has(slug))
      throw new Error(`Invalid or duplicate icon slug: ${slug}`)
    if (desktopAsset?.usage !== 'desktop-selected' || desktopAsset.status === 'candidate'
      || !['official', 'generated'].includes(desktopAsset.kind) || !/^v[1-9]\d*$/.test(desktopAsset.version)) {
      throw new Error(`Expected a selected desktop asset: ${slug}`)
    }
    const image = desktopAsset?.thumbnail
    const url = new URL(image?.url)
    if (url.origin !== mediaOrigin || url.username || url.password || url.search || url.hash
      || url.pathname !== `/desktop/app-icons/${desktopAsset.version}/${slug}.webp`
      || urls.has(url.href) || image.width !== 256 || image.height !== 256 || image.mime !== 'image/webp'
      || !Number.isSafeInteger(image.bytes) || image.bytes <= 0 || !/^[a-f0-9]{64}$/.test(image.sha256)) {
      throw new Error(`Invalid curated public thumbnail: ${slug}`)
    }
    slugs.add(slug)
    urls.add(url.href)
    return [slug, url.href]
  })
  return entries.sort(([a], [b]) => a.localeCompare(b, 'en'))
}

export function renderDesktopAssets(source) {
  const entries = readDesktopAssets(source)
  const sha256 = createHash('sha256').update(source).digest('hex')
  const rows = entries.map(([slug, url]) => `  '${slug}': '${url}',`).join('\n')
  return `// Generated by scripts/sync-catalog-icons.mjs from YunLeFun/icons ${catalogPath}.
// Source SHA-256: ${sha256}
// Only curated public assets may supply desktop icons; catalog metadata is not a source.
export const APP_ICON_URLS = Object.freeze({
${rows}
})

export function appIconUrl(slug: string): string {
  return Object.hasOwn(APP_ICON_URLS, slug) ? APP_ICON_URLS[slug as keyof typeof APP_ICON_URLS] : ''
}
`
}

export function renderNativeAssets(source) {
  const entries = readDesktopAssets(source)
  const manifest = JSON.parse(source)
  const assets = new Map(manifest.assets.map(asset => [asset.slug, asset]))
  const rows = entries.map(([slug, thumbnail]) => {
    const selected = assets.get(slug).desktopAsset
    let official = 'nil'
    if (selected.kind === 'official') {
      const source = selected.source
      const url = new URL(source?.url)
      if (source.kind !== 'official-source' || !/^[a-f0-9]{64}$/.test(source.sha256)
        || url.protocol !== 'https:' || url.username || url.password || url.search || url.hash
        || !/\.(?:svg|png|webp|jpe?g)$/i.test(url.pathname)) {
        throw new Error(`Invalid official icon source: ${slug}`)
      }
      official = JSON.stringify(url.href)
    }
    return `        ${JSON.stringify(slug)}: Asset(official: ${official}, thumbnail: ${JSON.stringify(thumbnail)}),`
  }).join('\n')
  const sha256 = createHash('sha256').update(source).digest('hex')
  return `// Generated by apps/desktop/scripts/sync-catalog-icons.mjs. Do not edit.
// Source: ${catalogURL}
// Source SHA-256: ${sha256}
// Shared by iOS and macOS; only selected assets, never candidates or archived artwork.
enum CatalogIconAssets {
    struct Asset: Equatable, Sendable {
        let official: String?
        let thumbnail: String
        var revision: String? = nil
    }
    static let bySlug: [String: Asset] = [
${rows}
    ]
}
`
}

async function main() {
  const args = process.argv.slice(2)
  const sourceIndex = args.indexOf('--source')
  const location = args[sourceIndex + 1]
  if (sourceIndex < 0 || !location || location.startsWith('--'))
    throw new Error(`Usage: pnpm icons:sync --source /path/to/YunLeFun/icons|${catalogURL} [--check]`)
  let source
  if (location.startsWith('https://')) {
    if (location !== catalogURL)
      throw new Error('Only the canonical online catalog URL is supported')
    source = await readOnlineCatalog()
  }
  else {
    source = await readFile(path.resolve(location, catalogPath), 'utf8')
  }
  // Validate every output before changing any checked-in snapshot.
  const outputs = [
    [new URL('../shared/app-icons.ts', import.meta.url), renderDesktopAssets(source)],
    [new URL('../../ios/YunleFun/Services/CatalogIconAssets.generated.swift', import.meta.url), renderNativeAssets(source)],
  ]
  if (args.includes('--check')) {
    for (const [target, output] of outputs) {
      if (await readFile(target, 'utf8') !== output)
        throw new Error(`Icon snapshot differs from the central catalog: ${fileURLToPath(target)}; run icons:sync`)
    }
    console.info('Verified desktop, iOS and macOS icon snapshots against YunLeFun/icons.')
    return
  }
  for (const [target, output] of outputs)
    await writeFile(target, output)
  console.info(`Synced ${readDesktopAssets(source).length} selected icons for desktop, iOS and macOS from YunLeFun/icons.`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  await main()
