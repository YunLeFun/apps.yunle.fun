import { existsSync, readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'

const browser = readFileSync(new URL('../../app/composables/useBrowser.ts', import.meta.url), 'utf8')
const contract = readFileSync(new URL('../../app/host-runtime/index.ts', import.meta.url), 'utf8')
const apiPlugin = readFileSync(new URL('../../app/plugins/api.ts', import.meta.url), 'utf8')
const loginPage = readFileSync(new URL('../../app/pages/login/index.vue', import.meta.url), 'utf8')
const userStore = readFileSync(new URL('../../app/stores/user.ts', import.meta.url), 'utf8')
const native = readFileSync(new URL('../../ios/App/App/WebViewController.swift', import.meta.url), 'utf8')
const nativePlugin = readFileSync(new URL('../../ios/App/App/InAppWebViewPlugin.swift', import.meta.url), 'utf8')
const androidPlugin = readFileSync(new URL('../../android/app/src/main/java/fun/yunle/apps/HostRuntimePlugin.kt', import.meta.url), 'utf8')
const androidAuthorizationSheet = readFileSync(new URL('../../android/app/src/main/java/fun/yunle/apps/AuthorizationConsentSheet.kt', import.meta.url), 'utf8')
const androidAppMenuSheet = readFileSync(new URL('../../android/app/src/main/java/fun/yunle/apps/AppMenuSheet.kt', import.meta.url), 'utf8')
const androidShareIcon = readFileSync(new URL('../../android/app/src/main/res/drawable/ic_app_menu_share.xml', import.meta.url), 'utf8')
const androidOpenBrowserIcon = readFileSync(new URL('../../android/app/src/main/res/drawable/ic_app_menu_open_browser.xml', import.meta.url), 'utf8')
const androidImageLoader = readFileSync(new URL('../../android/app/src/main/java/fun/yunle/apps/BoundedHttpsImageLoader.kt', import.meta.url), 'utf8')
const androidWebView = readFileSync(new URL('../../android/app/src/main/java/fun/yunle/apps/HostWebViewActivity.kt', import.meta.url), 'utf8')
const androidManifest = readFileSync(new URL('../../android/app/src/main/AndroidManifest.xml', import.meta.url), 'utf8')
const androidDebugManifest = readFileSync(new URL('../../android/app/src/debug/AndroidManifest.xml', import.meta.url), 'utf8')
const manifest = JSON.parse(readFileSync(new URL('../../package.json', import.meta.url), 'utf8'))

describe('native WebView authorization boundary', () => {
  it('does not expose SSO or host credentials through window.ylf', () => {
    expect(native).not.toContain('getAuthCode')
    expect(native).not.toContain('authReady')
    expect(native).not.toContain('refreshToken')
    expect(browser).not.toContain('auth?:')
    expect(browser).not.toContain('resolveAuthContext')
    expect(contract).not.toContain('accessToken')
    expect(contract).not.toContain('refreshToken')
  })

  it('uses only the authenticated CloudBase session for native authorization', () => {
    expect(userStore).not.toContain('NATIVE_TEST_SESSION_KEY')
    expect(userStore).not.toContain('nativeTestSession')
    expect(apiPlugin).toContain('userStore.accessToken')
    expect(apiPlugin).not.toContain('nativeTestSession')
    expect(apiPlugin).not.toContain('hostSession')
  })

  it('lets fixed test accounts use the standard username and password form', () => {
    expect(loginPage).toContain('signInWithPassword')
    expect(loginPage).toContain('params.username = passwordAccount.value')
    expect(loginPage).not.toContain('nativeTestChallengeId')
    expect(loginPage).not.toContain('/api/auth/native-test-session/exchange')
    expect(loginPage).not.toContain('模拟验证码')
  })

  it('removes the bespoke native authorization service', () => {
    expect(manifest.dependencies).not.toHaveProperty('@yunlefun/sso')
    expect(existsSync(new URL('../../server/utils/jsapi-auth.ts', import.meta.url))).toBe(false)
    expect(existsSync(new URL('../../server/api/jsapi/auth/code.post.ts', import.meta.url))).toBe(false)
    expect(existsSync(new URL('../../server/api/jsapi/auth/exchange.post.ts', import.meta.url))).toBe(false)
  })

  it('broadcasts identity changes generically while retaining only legacy native cookie cleanup', () => {
    expect(nativePlugin).toContain(`("play.yunle.fun", "__Host-ylf_play_session")`)
    expect(nativePlugin).toContain(`("cms.yunle.fun", "__Host-ylf-cms-session")`)
    expect(androidPlugin).toContain(`Triple("https://play.yunle.fun/", "__Host-ylf_play_session", true)`)
    expect(androidPlugin).toContain(`Triple("https://cms.yunle.fun/", "__Host-ylf-cms-session", true)`)
    expect(nativePlugin).not.toContain('identityAwareHosts')
    expect(androidWebView).not.toContain('IDENTITY_AWARE_HOSTS')
    expect(nativePlugin).not.toContain('__Host-dayun-kicker-session')
    expect(androidPlugin).not.toContain('__Host-dayun-kicker-session')
    expect(nativePlugin).toContain(`self?.sessions\n                    .forEach { $0.notifyHostIdentityChanged() }`)
    expect(androidWebView).toContain(`window.dispatchEvent(new CustomEvent('ylf:identityChanged'))`)
  })

  it('places the account consent prompt in the native plugin seam', () => {
    expect(contract).toContain('confirmAuthorization: (options:')
    expect(contract).toContain('applicationOrigin: string')
    expect(contract).toContain('applicationIconUrl?: string')
    expect(contract).toContain('accountAvatarUrl?: string')
    expect(nativePlugin).toContain('CAPPluginMethod(name: "confirmAuthorization"')
    expect(nativePlugin).toContain('@objc func confirmAuthorization')
    expect(nativePlugin).toContain('AuthorizationConsentViewController')
    expect(nativePlugin).toContain('sheet.sheetPresentationController')
    expect(nativePlugin).toContain('context.maximumDetentValue * 0.76')
    expect(nativePlugin).toContain('contentSizeCategory.isAccessibilityCategory')
    expect(nativePlugin).toContain('verticalSizeClass != .compact')
    expect(nativePlugin).toContain('presentation.detents = [comfortable, .large()]')
    expect(nativePlugin).toContain('"将向 \\(content.applicationName) 提供"')
    expect(nativePlugin).toContain('"使用此账号继续"')
    expect(nativePlugin).toContain('choice == .current')
    expect(androidPlugin).toContain('AuthorizationConsentSheet(')
    expect(androidAuthorizationSheet).toContain('BottomSheetDialog')
    expect(androidAuthorizationSheet).toContain(`"将向 \${content.applicationName} 提供"`)
    expect(androidAuthorizationSheet).toContain(`"以「\${shortAccountName()}」登录"`)
    expect(androidPlugin).toContain('choice == AuthorizationSheetChoice.CURRENT')
  })

  it('pauses the page deadline while the native consent sheet is visible', () => {
    expect(contract).toContain('requestId: string')
    expect(nativePlugin).toContain('pauseAuthorizationTimeout(requestId: requestId)')
    expect(nativePlugin).toContain('resumeAuthorizationTimeout(requestId: requestId)')
    expect(androidPlugin).toContain('presenter.pauseAuthorizationTimeout(requestId)')
    expect(androidPlugin).toContain('presenter.resumeAuthorizationTimeout(requestId)')
    expect(nativePlugin).toContain('_ = vc.pauseAuthorizationTimeout(requestId: requestId)')
    expect(androidPlugin).toContain('hostActivity.get()?.pauseAuthorizationTimeout(requestId)')
    expect(native).toContain('authorizationConsentTimeoutSeconds')
    expect(androidWebView).toContain('AUTHORIZATION_CONSENT_TIMEOUT_MS')
    expect(nativePlugin).toContain('guard authorizationSession.resumeAuthorizationTimeout(requestId: requestId) else')
    expect(nativePlugin).toContain('sheet?.expire()')
    expect(androidPlugin).toContain('if (!presenter.resumeAuthorizationTimeout(requestId))')
    expect(androidPlugin).toContain('sheet.expire()')
  })

  it('bounds authorization image transport and decoded pixels on both platforms', () => {
    expect(nativePlugin).toContain('BoundedHTTPSImageLoader')
    expect(nativePlugin).toContain('AuthorizationImageDecoder')
    expect(nativePlugin).toContain('CGImageSourceCreateThumbnailAtIndex')
    expect(nativePlugin).toContain('maximumSourcePixels')
    expect(nativePlugin).toContain('received.count <= maximumBytes - data.count')
    expect(nativePlugin).toContain('willPerformHTTPRedirection')
    expect(nativePlugin).toContain('completionHandler(nil)')
    expect(nativePlugin).not.toContain('URLSession.shared.downloadTask')
    expect(androidAuthorizationSheet).toContain('BoundedHttpsImageLoader.load')
    expect(androidAppMenuSheet).toContain('BoundedHttpsImageLoader.load')
    expect(androidImageLoader).toContain('decodeBoundedImage')
    expect(androidImageLoader).toContain('inJustDecodeBounds = true')
    expect(androidImageLoader).toContain('MAXIMUM_SOURCE_PIXELS')
    expect(androidImageLoader).toContain('inSampleSize = sampleSize')
  })

  it('maps every native Sheet dismissal to one cancel decision', () => {
    expect(nativePlugin).toContain('presentationControllerDidDismiss')
    expect(nativePlugin).toContain('complete(.cancel, dismiss: false)')
    expect(androidAuthorizationSheet).toContain('setOnCancelListener')
    expect(androidAuthorizationSheet).toContain('setOnDismissListener')
    expect(androidAuthorizationSheet).toContain('if (completed) return')
  })

  it('uses one protocol with platform-native adapters', () => {
    expect(contract).toContain('registerPlugin<HostRuntimePlugin>(\'HostRuntime\')')
    expect(nativePlugin).toContain('public let jsName = "HostRuntime"')
    expect(androidPlugin).toContain('@CapacitorPlugin(name = "HostRuntime")')
  })

  it('keeps pending authorization alive across the local Apps login route', () => {
    expect(contract).toContain('requestHostLogin:')
    expect(contract).toContain('resumeAuthorizationAfterLogin:')
    expect(contract).toContain('cancelAuthorizationLogin:')
    expect(loginPage).toContain('resumeAuthorizationAfterLogin({ requestId })')
    expect(loginPage).toContain('cancelAuthorizationLogin({ requestId })')
    expect(loginPage).toContain('登录后返回原应用')
    expect(loginPage).toContain('登录本身不会自动授权')
    expect(loginPage).toContain('重试返回原应用')
    expect(loginPage).toContain('returningToApplication.value = true')
    expect(loginPage).toContain('returningToApplication.value = false')
    expect(loginPage).toContain('pendingNativeAuthorization || nativeAuthorizationReturnError')
    expect(nativePlugin).toContain('CAPPluginMethod(name: "requestHostLogin"')
    expect(nativePlugin).toContain('CAPPluginMethod(name: "resumeAuthorizationAfterLogin"')
    expect(nativePlugin).toContain('CAPPluginMethod(name: "cancelAuthorizationLogin"')
    expect(nativePlugin).toContain('authorizationEvent(requestId: requestId)')
    expect(androidPlugin).toContain('fun requestHostLogin')
    expect(androidPlugin).toContain('fun resumeAuthorizationAfterLogin')
    expect(androidPlugin).toContain('fun cancelAuthorizationLogin')
    expect(androidPlugin).toContain('Intent.FLAG_ACTIVITY_REORDER_TO_FRONT')
    expect(androidManifest).toContain('android:launchMode="singleTop"')
    expect(androidWebView).toContain('fun authorizationEvent(requestId: String)')
  })

  it('brings a reused Android WebView session back to the foreground', () => {
    const openMethod = androidPlugin.slice(
      androidPlugin.indexOf('fun open(call: PluginCall)'),
      androidPlugin.indexOf('fun close(call: PluginCall)'),
    )
    expect(openMethod).toContain('currentActivity.applyOptions(call.data)')
    expect(openMethod).toContain('activity.startActivity(')
    expect(openMethod).toContain('Intent.FLAG_ACTIVITY_REORDER_TO_FRONT')
    expect(openMethod).toContain('Intent.FLAG_ACTIVITY_SINGLE_TOP')
  })

  it('uses system authentication surfaces when another account is selected', () => {
    expect(contract).toContain('authorizeWithOtherAccount:')
    expect(nativePlugin).toContain('CAPPluginMethod(name: "authorizeWithOtherAccount"')
    expect(nativePlugin).toContain('@objc func authorizeWithOtherAccount')
    expect(nativePlugin).toContain('case other')
    expect(nativePlugin).toContain('complete(.other)')
    expect(native).toContain('ASWebAuthenticationSession(')
    expect(androidPlugin).toContain('fun authorizeWithOtherAccount')
    expect(androidAuthorizationSheet).toContain('OTHER("other")')
    expect(androidAuthorizationSheet).toContain('complete(AuthorizationSheetChoice.OTHER)')
    expect(androidWebView).toContain('CustomTabsIntent.Builder()')
  })

  it('opens trusted external OAuth in a state-bound system authentication session', () => {
    expect(native).toContain('"openAuthSession": .trusted')
    expect(native).toContain('NativeExternalAuthorizationProtocol.readRequest')
    expect(native).toContain('callback.path == "/external"')
    expect(native).toContain('ASWebAuthenticationSession(')
    expect(androidWebView).toContain('"openAuthSession" to JsapiAccess.TRUSTED')
    expect(androidWebView).toContain('ExternalAuthProtocol.readRequest')
    expect(androidManifest).toContain('android:path="/external"')
  })

  it('binds Android sensitive calls to an unforgeable main-frame source origin', () => {
    expect(androidWebView).toContain('WebViewCompat.addWebMessageListener(')
    expect(androidWebView).toContain('sourceOrigin: Uri')
    expect(androidWebView).toContain('isMainFrame: Boolean')
    expect(androidWebView).toContain('if (!isMainFrame)')
    expect(androidWebView).toContain('private fun isTrustedOrigin(origin: Uri)')
    expect(androidWebView).not.toContain('webView.addJavascriptInterface(')
    expect(androidWebView).not.toContain('setOf("*")')
  })

  it('disables Android cleartext traffic outside explicit debug builds', () => {
    expect(androidManifest).toContain('android:usesCleartextTraffic="false"')
    expect(androidDebugManifest).toContain('android:usesCleartextTraffic="true"')
  })

  it('keeps a native Android exit anchor when trusted pages enter immersive chrome', () => {
    expect(browser).toContain('resolveAppIconPresentation')
    expect(browser).toContain('iconAssets: app.iconAssets')
    expect(browser).toContain('preferOriginal: true')
    expect(browser).toContain('getPublicCloudbaseStorageUrl')
    expect(browser).toContain('app: nativeAppInfo')
    expect(androidWebView).toContain('displayMode = "titlebar"')
    expect(androidWebView).toContain('contentDescription = "更多"')
    expect(androidWebView).toContain('floatingMenuButton.visibility')
    expect(androidWebView).toContain('AppMenuSheet(')
    expect(androidAppMenuSheet).toContain('BottomSheetDialog')
    expect(androidAppMenuSheet).toContain('NestedScrollView')
    expect(androidAppMenuSheet).toContain('DETAILS("details"')
    expect(androidAppMenuSheet).toContain('SHARE("share"')
    expect(androidAppMenuSheet).toContain('R.drawable.ic_app_menu_lock')
    expect(androidAppMenuSheet).toContain('LinearLayout.LayoutParams(dp(16), dp(16))')
    expect(androidAppMenuSheet).toContain('includeFontPadding = false')
    expect(androidAppMenuSheet).toContain('COPY_LINK("copy_link"')
    expect(androidAppMenuSheet).toContain('OPEN_BROWSER("open_browser"')
    expect(androidAppMenuSheet).toContain('RELOAD("reload"')
    expect(androidAppMenuSheet).toContain('END("end"')
    expect(androidAppMenuSheet).toContain('Configuration.UI_MODE_NIGHT_YES')
    expect(androidWebView).toContain('https')
    expect(androidWebView).toContain('apps.yunle.fun')
    expect(androidWebView).toContain('fragment("reviews")')
    expect(native).toContain('case copyLink = "copy_link"')
    expect(native).toContain('case openBrowser = "open_browser"')
    expect(native).toContain('makeActionRow(.end)')
    expect(native).toContain('BoundedHTTPSImageLoader(maximumBytes: 2_000_000)')
    expect(native).toContain('let scroll = UIScrollView()')
    expect(native).toContain('adjustsFontForContentSizeCategory = true')
    expect(native).toContain('constraint(greaterThanOrEqualToConstant: 44)')
    expect(androidWebView).not.toContain('contentDescription = "关闭"')
    expect(androidWebView).toContain('"setTitleBarVisible" to JsapiAccess.OPEN')
    expect(androidWebView).toContain('WindowInsetsCompat.Type.systemBars()')
  })

  it('exposes bounded trusted native haptics on iOS and Android', () => {
    expect(native).toContain('"haptic": .trusted')
    expect(native).toContain('UIImpactFeedbackGenerator(style: .heavy)')
    expect(native).toContain('UINotificationFeedbackGenerator().notificationOccurred(.success)')
    expect(androidWebView).toContain('"haptic" to JsapiAccess.TRUSTED')
    expect(androidWebView).toContain('HapticFeedbackConstants.CONFIRM')
    expect(androidWebView).toContain('bad request: unsupported haptic style')
  })

  it('uses the complete Material Design share vector path', () => {
    expect(androidShareIcon).toContain('c0.54,0.5 1.25,0.81 2.04,0.81')
    expect(androidShareIcon).toContain('c-1.66,0 -3,1.34 -3,3')
    expect(androidShareIcon).not.toContain('A3,3')
  })

  it('uses the Material Design open-in-browser vector instead of an image glyph', () => {
    expect(androidOpenBrowserIcon).toContain('M12,10l-4,4h3v6h2v-6h3l-4,-4z')
    expect(androidOpenBrowserIcon).not.toContain('M7,15h4')
  })
})
